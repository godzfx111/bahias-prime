async function iniciarAula() {

  const autenticado =
    await verificarUsuario();


  if (!autenticado) {

    return;

  }


  await carregarProgressoAulas();


  const id =
    pegarIdAula();


  if (
    !id ||
    id < 1 ||
    id > 10
  ) {

    window.location.href =
      "redacao.html";

    return;

  }


  renderizarAula(
    id
  );

}


iniciarAula();
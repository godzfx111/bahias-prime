/* =========================================
   USUÁRIO + PROGRESSO REAL
========================================= */

let usuarioAula = null;

let aulasConcluidas =
  new Set();

let aulaAtualId = null;


/* =========================================
   VERIFICAR USUÁRIO
========================================= */

async function verificarUsuario() {

  const {
    data: { session },
    error
  } =
    await supabaseClient
      .auth
      .getSession();


  if (
    error ||
    !session
  ) {

    window.location.href =
      "../login.html";

    return false;

  }


  usuarioAula =
    session.user;


  return true;

}


/* =========================================
   CARREGAR PROGRESSO
========================================= */

async function carregarProgressoAulas() {

  const {
    data,
    error
  } =
    await supabaseClient
      .from(
        "essay_lesson_progress"
      )
      .select(
        "lesson_id"
      )
      .eq(
        "user_id",
        usuarioAula.id
      );


  if (error) {

    console.error(
      "Erro ao carregar progresso:",
      error
    );

    aulasConcluidas =
      new Set();

    return;

  }


  aulasConcluidas =
    new Set(
      (data || []).map(
        item =>
          Number(
            item.lesson_id
          )
      )
    );

}


/* =========================================
   SALVAR AULA CONCLUÍDA
========================================= */

async function salvarAulaConcluida(
  lessonId
) {

  if (
    !usuarioAula ||
    aulasConcluidas.has(
      Number(lessonId)
    )
  ) {

    return true;

  }


  const {
    error
  } =
    await supabaseClient
      .from(
        "essay_lesson_progress"
      )
      .upsert(
        {
          user_id:
            usuarioAula.id,

          lesson_id:
            Number(lessonId),

          completed_at:
            new Date()
              .toISOString()
        },
        {
          onConflict:
            "user_id,lesson_id"
        }
      );


  if (error) {

    console.error(
      "Erro ao salvar aula:",
      error
    );

    return false;

  }


  aulasConcluidas.add(
    Number(lessonId)
  );


  atualizarProgressoCurso();

  atualizarEstadoFinal(
    lessonId
  );


  return true;

}


/* =========================================
   PROGRESSO DO CURSO
========================================= */

function atualizarProgressoCurso() {

  const concluidas =
    aulasConcluidas.size;


  const percentual =
    Math.round(
      (
        concluidas /
        10
      ) * 100
    );


  const texto =
    document.getElementById(
      "courseProgressText"
    );


  const barra =
    document.getElementById(
      "courseProgressBar"
    );


  if (texto) {

    texto.textContent =
      `${concluidas}/10 • ${percentual}%`;

  }


  if (barra) {

    barra.style.width =
      `${percentual}%`;

  }

}


